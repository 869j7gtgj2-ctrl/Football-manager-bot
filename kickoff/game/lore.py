def euro_for(league: int, rank: int) -> str | None:
    for last, code in EURO.get(league, []):
        if rank <= last:
            return code
    return None


def generic_story(name: str, city: str, rank: int, total: int, league: str) -> str:
    if rank <= 2:
        return f"{name} з міста {city} — один із головних претендентів на титул у {league}. Тиск величезний, але й нагорода теж."
    if rank <= max(3, total // 3):
        return f"{name} — міцний клуб верхньої половини {league}. Правильний тренер може вивести команду в єврокубки."
    if rank <= total * 2 // 3:
        return f"{name} з міста {city} — типовий середняк {league}. Тут можна спокійно будувати команду своєї мрії."
    return f"{name} — аутсайдер {league}. Справжній виклик: вижити, а потім здивувати всіх."
